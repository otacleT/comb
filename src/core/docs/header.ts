export const DOC_MARKER = '<!-- generated by comb';
const STAMPED_RE = /^<!-- generated by comb from (sha256:[0-9a-f]{16})/;

const firstLine = (text: string): string => {
  const nl = text.indexOf('\n');
  return nl < 0 ? text : text.slice(0, nl);
};

/** A generated document starts with the marker; a stamped one also records the source hash it was generated from. */
export function docHeader(text: string): { generated: boolean; hash: string | null } {
  const first = firstLine(text);
  if (!first.startsWith(DOC_MARKER)) return { generated: false, hash: null };
  return { generated: true, hash: STAMPED_RE.exec(first)?.[1] ?? null };
}

export const stampedHeader = (hash: string): string => `<!-- generated by comb from ${hash}; edit the specs, not this file -->`;

/** Replaces the first line (the marker) with the stamped header. */
export function stampDoc(text: string, hash: string): string {
  const nl = text.indexOf('\n');
  return `${stampedHeader(hash)}${nl < 0 ? '\n' : text.slice(nl)}`;
}

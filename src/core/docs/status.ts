import { diag, type Diagnostic } from '../diagnostics.js';
import { checkCitations, extractCitations, uncitedSections, type DocRefs } from './citations.js';
import { docHeader } from './header.js';
import type { Profile } from './profile.js';
import { sourceHash, type DocInputs } from './sources.js';

export type DocState = 'missing' | 'stale' | 'done' | 'user-owned';

export interface DocOutputStatus {
  id: string;
  /** Root-relative: `<documents.dir>/<output path>`. */
  path: string;
  state: DocState;
  sourceHash: string;
  recordedHash: string | null;
}

export interface DocsStatus {
  profile: string;
  dir: string;
  outputs: DocOutputStatus[];
  /** Canonical requirements that no generated document cites. */
  uncovered: string[];
}

export function docsStatus(
  profile: Profile,
  dir: string,
  inputs: DocInputs,
  refs: DocRefs,
  texts: ReadonlyMap<string, string | null>,
): { status: DocsStatus; diagnostics: Diagnostic[] } {
  const diagnostics: Diagnostic[] = [];
  const cited = new Set<string>();
  const outputs = profile.outputs.map((o): DocOutputStatus => {
    const path = `${dir}/${o.path}`;
    const hash = sourceHash(o.sources, inputs);
    const text = texts.get(path) ?? null;
    if (text === null) {
      diagnostics.push(diag('error', 'DOC_MISSING', `${path} has not been generated`, { file: path }, 'Run /comb:docs'));
      return { id: o.id, path, state: 'missing', sourceHash: hash, recordedHash: null };
    }
    const header = docHeader(text);
    if (!header.generated) {
      diagnostics.push(diag('error', 'DOC_USER_OWNED', `${path} exists but was not generated by comb`, { file: path, line: 1 },
        'Move it away, or set documents.dir in comb/config.yaml to another folder'));
      return { id: o.id, path, state: 'user-owned', sourceHash: hash, recordedHash: null };
    }
    diagnostics.push(...checkCitations(text, path, refs), ...uncitedSections(text, path));
    for (const id of extractCitations(text).requirements) cited.add(id);
    if (header.hash !== hash) {
      const t = { file: path, line: 1 };
      diagnostics.push(
        header.hash !== null
          ? diag('error', 'DOC_STALE', `${path} was generated from older sources`, t, 'Run /comb:docs')
          : header.writtenFor === hash
            ? diag('error', 'DOC_STALE', `${path} is not stamped yet`, t, 'Run comb docs stamp')
            : diag('error', 'DOC_STALE', `${path} was not written from the current sources`, t,
                'Rewrite it with /comb:docs, starting from the marker that comb instructions docs gives'),
      );
      return { id: o.id, path, state: 'stale', sourceHash: hash, recordedHash: header.hash };
    }
    return { id: o.id, path, state: 'done', sourceHash: hash, recordedHash: header.hash };
  });
  const uncovered = [...refs.requirements].filter((id) => !cited.has(id)).sort();
  if (uncovered.length > 0 && outputs.some((o) => o.state === 'done' || o.state === 'stale')) {
    diagnostics.push(diag('warning', 'DOC_UNCOVERED', `no document cites ${uncovered.join(', ')}`, undefined, 'Cover them in features.md, screens.md or flows.md'));
  }
  return { status: { profile: profile.id, dir, outputs, uncovered }, diagnostics };
}

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { runCli } from '../../src/cli/app.js';
import { TIGHTEN_QUESTIONS } from '../helpers/archive.js';
import { CONFIG_YAML, DECISIONS_MD, ORDER_SPEC } from '../helpers/fixtures.js';
import { makeProject } from '../helpers/project.js';

const BODIES: Record<string, string> = {
  'product.md': '# Shop\n\nA shop (config:context).\n\n## Capabilities\n- Orders (REQ-ORDER-001)\n\n## Gaps\n- None.\n',
  'features.md': '# Features\n\n## Ordering\nOrders are created at Buy (REQ-ORDER-001) and paid within 3 days (REQ-ORDER-002).\n',
  'screens.md': '# Screens\n\nNo screen is specified.\n\n## Gaps\n- No screen is specified for REQ-ORDER-001.\n',
  'flows.md': '# Flows\n\n## Buying\n1. Buy, then pay (REQ-ORDER-001, REQ-ORDER-002).\n',
  'decisions.md': '# Decisions\n\n## Pricing\nThe price is fixed at Buy (D-021).\n',
  'open-questions.md': '# Open questions\n\n## Payments\n- How long may payment take? (tighten-payment#Q-1)\n',
};

const project = (extra: Record<string, string> = {}) =>
  makeProject({
    'comb/config.yaml': `${CONFIG_YAML}context: A shop for second-hand goods.\n`,
    'comb/specs/order-lifecycle/spec.md': ORDER_SPEC,
    'comb/decisions.md': DECISIONS_MD,
    'comb/changes/archive/2026-10-06-tighten-payment/questions.md': TIGHTEN_QUESTIONS,
    ...extra,
  });

/** What the agent does: write each document starting with the marker `comb instructions docs` hands out. */
const writeDocs = async (root: string, dir = 'docs', skip: string[] = []) => {
  const outputs = JSON.parse((await runCli(['instructions', 'docs', '--json'], root)).stdout).data.outputs as { path: string; marker: string }[];
  mkdirSync(join(root, dir), { recursive: true });
  for (const o of outputs) {
    const name = o.path.slice(dir.length + 1);
    if (!skip.includes(name)) writeFileSync(join(root, o.path), `${o.marker}\n${BODIES[name]}`);
  }
};

const json = async (args: string[], root: string) => {
  const r = await runCli([...args, '--json'], root);
  return { code: r.code, env: JSON.parse(r.stdout) };
};
const states = (env: { data: { outputs: { path: string; state: string }[] } }) => Object.fromEntries(env.data.outputs.map((o) => [o.path, o.state]));

describe('comb docs', () => {
  it('reports every document missing before the first generation', async () => {
    const { code, env } = await json(['docs'], project());
    expect(code).toBe(1);
    expect(Object.values(states(env))).toEqual(Array(6).fill('missing'));
    expect(env.data.outputs[0].path).toBe('docs/product.md');
  });

  it('stamps freshly written documents and then reports them done', async () => {
    const root = project();
    await writeDocs(root);
    const stamp = await json(['docs', 'stamp'], root);
    expect(stamp.code).toBe(0);
    expect(stamp.env.data.stamped).toHaveLength(6);
    const { code, env } = await json(['docs'], root);
    expect(code).toBe(0);
    expect(env.diagnostics).toEqual([]);
    expect(Object.values(states(env))).toEqual(Array(6).fill('done'));
    expect(readFileSync(join(root, 'docs/product.md'), 'utf8').split('\n')[0]).toMatch(/^<!-- generated by comb from sha256:[0-9a-f]{16}; edit the specs, not this file -->$/);
  });

  it('marks stale only the documents whose sources changed, and stamp does not hide it', async () => {
    const root = project();
    await writeDocs(root);
    await json(['docs', 'stamp'], root);
    writeFileSync(join(root, 'comb/decisions.md'), `${DECISIONS_MD}\n## D-022: Another\n- **Date:** 2026-10-08\n\nRule.\n\n**Why:** w\n`);
    expect(states((await json(['docs'], root)).env)).toEqual({
      'docs/product.md': 'done',
      'docs/features.md': 'done',
      'docs/screens.md': 'done',
      'docs/flows.md': 'done',
      'docs/decisions.md': 'stale',
      'docs/open-questions.md': 'done',
    });
    writeFileSync(join(root, 'comb/specs/order-lifecycle/spec.md'), ORDER_SPEC.replace('Pay within 3 days.', 'Pay within 2 days.'));
    const stamp = await json(['docs', 'stamp'], root);
    expect(stamp.env.data.stamped).toEqual([]);
    expect(stamp.env.data.skipped.find((s: { path: string }) => s.path === 'docs/features.md').reason).toContain('stale');
    expect(states((await json(['docs'], root)).env)['docs/features.md']).toBe('stale');
  });

  it('never stamps or overwrites a file the user wrote, and ignores files that are not outputs', async () => {
    const root = project({ 'docs/product.md': '# Mine\n', 'docs/README.md': '# Readme\n' });
    await writeDocs(root, 'docs', ['product.md']);
    const stamp = await json(['docs', 'stamp'], root);
    expect(stamp.env.data.skipped).toEqual([{ path: 'docs/product.md', reason: 'user-owned' }]);
    expect(readFileSync(join(root, 'docs/product.md'), 'utf8')).toBe('# Mine\n');
    expect(readFileSync(join(root, 'docs/README.md'), 'utf8')).toBe('# Readme\n');
    const { code, env } = await json(['docs'], root);
    expect(code).toBe(1);
    expect(env.diagnostics.map((d: { code: string }) => d.code)).toEqual(['DOC_USER_OWNED']);
  });

  it('writes to documents.dir', async () => {
    const root = project({ 'comb/config.yaml': `${CONFIG_YAML}context: A shop.\ndocuments:\n  dir: site/docs\n` });
    await writeDocs(root, 'site/docs');
    await json(['docs', 'stamp'], root);
    const { code, env } = await json(['docs'], root);
    expect(code).toBe(0);
    expect(env.data.outputs.map((o: { path: string }) => o.path)[0]).toBe('site/docs/product.md');
  });

  it('rejects an unknown action', async () => {
    const { code, env } = await json(['docs', 'nope'], project());
    expect(code).toBe(2);
    expect(env.diagnostics[0].code).toBe('USAGE_ERROR');
  });

  it('does not stamp documents written before their sources changed', async () => {
    const root = project();
    await writeDocs(root);
    writeFileSync(join(root, 'comb/specs/order-lifecycle/spec.md'), ORDER_SPEC.replace('Pay within 3 days.', 'Pay within 2 days.'));
    const stamp = await json(['docs', 'stamp'], root);
    expect(stamp.env.data.stamped).toEqual(['docs/decisions.md', 'docs/open-questions.md']);
    expect(stamp.env.data.skipped.map((x: { reason: string }) => x.reason)).toEqual(Array(4).fill('sources changed since it was written: rewrite it with /comb:docs'));
    expect(states((await json(['docs'], root)).env)['docs/features.md']).toBe('stale');
  });

  it('reports an output path that is a folder instead of crashing', async () => {
    const root = project();
    mkdirSync(join(root, 'docs/flows.md'), { recursive: true });
    const { code, env } = await json(['docs'], root);
    expect(code).toBe(1);
    expect(states(env)['docs/flows.md']).toBe('user-owned');
    const stamp = await json(['docs', 'stamp'], root);
    expect(stamp.code).toBe(0);
    expect(stamp.env.data.skipped).toContainEqual({ path: 'docs/flows.md', reason: 'user-owned' });
  });
});

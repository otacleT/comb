import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { loadProfile } from '../../../src/core/docs/profile.js';
import { TEMPLATES_DIR } from '../../../src/templates-dir.js';
import { makeProject } from '../../helpers/project.js';

describe('loadProfile', () => {
  it('loads the built-in solo profile', () => {
    const { profile, diagnostics } = loadProfile(join(TEMPLATES_DIR, 'profiles', 'solo'));
    expect(diagnostics).toEqual([]);
    expect(profile!.id).toBe('solo');
    expect(profile!.outputs.map((o) => [o.id, o.path, o.sources])).toEqual([
      ['product', 'product.md', ['config', 'specs']],
      ['features', 'features.md', ['specs']],
      ['screens', 'screens.md', ['specs']],
      ['flows', 'flows.md', ['specs']],
      ['decisions', 'decisions.md', ['decisions']],
      ['open-questions', 'open-questions.md', ['open-questions']],
    ]);
    for (const o of profile!.outputs) {
      expect(o.template.startsWith('<!-- generated by comb -->\n'), o.id).toBe(true);
      expect(o.template, o.id).toContain('## Gaps');
      expect(o.audience, o.id).not.toBe('');
    }
    expect(profile!.skill).toContain('#Q-');
    expect(profile!.skill).toContain('config:context');
    expect(profile!.skill).toContain('<capability>#<Section heading>');
  });

  it('rejects a folder that is not a valid profile', () => {
    const ok = 'id: x\ntype: comb.document-profile\nversion: 1\noutputs:\n  - id: a\n    path: a.md\n    template: t.md\n    audience: me\n    sources: [specs]\n';
    const cases: Record<string, string>[] = [
      { 'SKILL.md': 's', 't.md': 't' },
      { 'profile.yaml': ok.replace('comb.document-profile', 'other'), 'SKILL.md': 's', 't.md': 't' },
      { 'profile.yaml': ok.replace('version: 1', 'version: 2'), 'SKILL.md': 's', 't.md': 't' },
      { 'profile.yaml': ok.replace('[specs]', '[code]'), 'SKILL.md': 's', 't.md': 't' },
      { 'profile.yaml': ok, 'SKILL.md': 's' },
      { 'profile.yaml': ok, 't.md': 't' },
    ];
    for (const files of cases) expect(loadProfile(makeProject(files)).diagnostics.map((d) => d.code)).toEqual(['CONFIG_INVALID']);
    expect(loadProfile(makeProject({ 'profile.yaml': ok, 'SKILL.md': 's', 't.md': 't' })).diagnostics).toEqual([]);
  });

  it('asks only for citation forms that exist', () => {
    const { profile } = loadProfile(join(TEMPLATES_DIR, 'profiles', 'solo'));
    const template = (id: string) => profile!.outputs.find((o) => o.id === id)!.template;
    expect(template('product')).toContain('<capability>#Purpose');
    expect(template('flows')).toContain('<capability>#States');
  });

  it('rejects duplicate outputs and paths that leave their folders', () => {
    const out = (id: string, path: string, template = 't.md') => `  - id: ${id}\n    path: ${path}\n    template: ${template}\n    audience: me\n    sources: [specs]\n`;
    const head = 'id: x\ntype: comb.document-profile\nversion: 1\noutputs:\n';
    for (const outputs of [out('a', 'a.md') + out('a', 'b.md'), out('a', 'a.md') + out('b', 'a.md'), out('a', '../a.md'), out('a', '/tmp/a.md'), out('a', 'a.md', '../t.md')]) {
      expect(loadProfile(makeProject({ 'profile.yaml': head + outputs, 'SKILL.md': 's', 't.md': 't' })).diagnostics.map((d) => d.code), outputs).toEqual(['CONFIG_INVALID']);
    }
  });
});

import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { stampDoc } from '../../../src/core/docs/header.js';
import { loadProfile } from '../../../src/core/docs/profile.js';
import { docInputs, docRefs, sourceHash } from '../../../src/core/docs/sources.js';
import { docsStatus } from '../../../src/core/docs/status.js';
import { loadArchivedQuestions, loadProject } from '../../../src/core/project/load.js';
import { TEMPLATES_DIR } from '../../../src/templates-dir.js';
import { TIGHTEN_QUESTIONS } from '../../helpers/archive.js';
import { CONFIG_YAML, DECISIONS_MD, ORDER_SPEC } from '../../helpers/fixtures.js';
import { makeProject } from '../../helpers/project.js';

const profile = loadProfile(join(TEMPLATES_DIR, 'profiles', 'solo')).profile!;

const setup = (extra: Record<string, string> = {}) => {
  const root = makeProject({
    'comb/config.yaml': `${CONFIG_YAML}context: A shop for second-hand goods.\n`,
    'comb/specs/order-lifecycle/spec.md': ORDER_SPEC,
    'comb/decisions.md': DECISIONS_MD,
    'comb/changes/archive/2026-10-06-tighten-payment/questions.md': TIGHTEN_QUESTIONS,
    ...extra,
  });
  const project = loadProject(root);
  const questions = loadArchivedQuestions(root);
  return { inputs: docInputs(project, questions), refs: docRefs(project, questions) };
};
const { inputs, refs } = setup();
const fresh = (id: string, body: string) =>
  stampDoc(`<!-- generated by comb -->\n${body}`, sourceHash(profile.outputs.find((o) => o.id === id)!.sources, inputs));

/** A complete, cited set of documents. */
const DOCS: Record<string, string> = {
  product: '# Shop\n\nA shop (config:context).\n\n## Capabilities\n- Orders (REQ-ORDER-001)\n\n## Gaps\n- None.\n',
  features: '# Features\n\n## Ordering\nOrders are created at Buy (REQ-ORDER-001) and paid within 3 days (REQ-ORDER-002).\n',
  screens: '# Screens\n\nNo screen is specified.\n\n## Gaps\n- No screen is specified for REQ-ORDER-001.\n',
  flows: '# Flows\n\n## Buying\n1. Buy, then pay (REQ-ORDER-001, REQ-ORDER-002).\n',
  decisions: '# Decisions\n\n## Pricing\nThe price is fixed at Buy (D-021).\n',
  'open-questions': '# Open questions\n\n## Payments\n- How long may payment take? (tighten-payment#Q-1)\n',
};
const texts = (overrides: Record<string, string | null> = {}) =>
  new Map(profile.outputs.map((o) => [`docs/${o.path}`, o.id in overrides ? overrides[o.id]! : fresh(o.id, DOCS[o.id]!)]));
const codes = (ds: { code: string; target?: { id?: string } }[]) => ds.map((d) => [d.code, d.target?.id]);

describe('docsStatus', () => {
  it('reports every output missing before the first generation, without a coverage warning', () => {
    const { status, diagnostics } = docsStatus(profile, 'docs', inputs, refs, new Map(profile.outputs.map((o) => [`docs/${o.path}`, null])));
    expect(status.outputs.map((o) => [o.path, o.state])).toEqual(profile.outputs.map((o) => [`docs/${o.path}`, 'missing']));
    expect(diagnostics.map((d) => d.code)).toEqual(Array(6).fill('DOC_MISSING'));
  });

  it('accepts a complete, cited and stamped set, including a document that only has Gaps', () => {
    const { status, diagnostics } = docsStatus(profile, 'docs', inputs, refs, texts());
    expect(diagnostics).toEqual([]);
    expect(status.outputs.every((o) => o.state === 'done' && o.recordedHash === o.sourceHash)).toBe(true);
    expect(status.uncovered).toEqual([]);
  });

  it('marks documents stale unless they were written for the current sources and stamped', () => {
    const current = (id: string) => sourceHash(profile.outputs.find((o) => o.id === id)!.sources, inputs);
    const rewrite = 'Rewrite it with /comb:docs, starting from the marker that comb instructions docs gives';
    const { status, diagnostics } = docsStatus(profile, 'docs', inputs, refs, texts({
      features: `<!-- generated by comb for ${current('features')} -->\n${DOCS.features}`,
      screens: `<!-- generated by comb for sha256:0000000000000000 -->\n${DOCS.screens}`,
      flows: `<!-- generated by comb -->\n${DOCS.flows}`,
      decisions: stampDoc(`<!-- generated by comb -->\n${DOCS.decisions}`, 'sha256:0000000000000000'),
    }));
    expect(status.outputs.filter((o) => o.state === 'stale').map((o) => o.id)).toEqual(['features', 'screens', 'flows', 'decisions']);
    expect(diagnostics.map((d) => [d.target?.file, d.fix])).toEqual([
      ['docs/features.md', 'Run comb docs stamp'],
      ['docs/screens.md', rewrite],
      ['docs/flows.md', rewrite],
      ['docs/decisions.md', 'Run /comb:docs'],
    ]);
  });

  it('counts a citation in the section heading', () => {
    const { diagnostics } = docsStatus(profile, 'docs', inputs, refs, texts({
      features: fresh('features', '# F\n\n## Ordering (REQ-ORDER-001, REQ-ORDER-002)\nOrders are created and paid.\n'),
    }));
    expect(diagnostics).toEqual([]);
  });

  it('rejects config:context when the project has no context', () => {
    const empty = setup({ 'comb/config.yaml': CONFIG_YAML });
    const doc = stampDoc(`<!-- generated by comb -->\n${DOCS.product}`, sourceHash(['config', 'specs'], empty.inputs));
    const { diagnostics } = docsStatus(profile, 'docs', empty.inputs, empty.refs, new Map([['docs/product.md', doc]]));
    expect(diagnostics.filter((d) => d.code.startsWith('REF_')).map((d) => d.code)).toEqual(['REF_EMPTY_CONTEXT']);
  });

  it('never treats a file without the marker as generated', () => {
    const { status, diagnostics } = docsStatus(profile, 'docs', inputs, refs, texts({ product: '# My notes\n<!-- generated by comb -->\n' }));
    expect(status.outputs[0]!.state).toBe('user-owned');
    expect(diagnostics.map((d) => d.code)).toContain('DOC_USER_OWNED');
  });

  it('checks citations against the canonical specs, the decision log and the archived questions', () => {
    const { diagnostics } = docsStatus(profile, 'docs', inputs, refs, texts({
      features: fresh('features', '# F\n\n## A\nX (REQ-ORDER-001, REQ-ORDER-002, REQ-ORDER-999, REQ-ORDER-010).\n'),
      decisions: fresh('decisions', '# D\n\n## P\nY (D-021, D-999).\n'),
      'open-questions': fresh('open-questions', '# O\n\n## Q\n- Z (tighten-payment#Q-1, seed#Q-9).\n'),
    }));
    expect(codes(diagnostics)).toEqual([
      ['REF_UNKNOWN_REQ', 'REQ-ORDER-999'],
      ['REF_UNKNOWN_REQ', 'REQ-ORDER-010'],
      ['REF_UNKNOWN_DECISION', 'D-999'],
      ['REF_UNKNOWN_QUESTION', 'seed#Q-9'],
    ]);
    expect(diagnostics[1]!.message).toContain('was removed');
  });

  it('rejects requirements that exist only in an active change', () => {
    const add = '## ADDED Requirements\n\n### Requirement: REQ-ORDER-003 Refund\nRefund.\n\n#### Scenario: s\n- **GIVEN** a\n';
    const active = setup({ 'comb/changes/add-refund/.comb.yaml': 'schema: comb.change/v1\nid: add-refund\ncreated: 2026-10-08\nbase: {}\n', 'comb/changes/add-refund/specs/order-lifecycle/spec.md': add });
    const doc = stampDoc(`<!-- generated by comb -->\n# F\n\n## A\nX (REQ-ORDER-001, REQ-ORDER-002, REQ-ORDER-003).\n`, sourceHash(['specs'], active.inputs));
    const { diagnostics } = docsStatus(profile, 'docs', active.inputs, active.refs, new Map([['docs/features.md', doc]]));
    expect(codes(diagnostics.filter((d) => d.code.startsWith('REF_')))).toEqual([['REF_UNKNOWN_REQ', 'REQ-ORDER-003']]);
  });

  it('warns about sections that cite nothing, except under Gaps', () => {
    const { diagnostics } = docsStatus(profile, 'docs', inputs, refs, texts({
      features: fresh('features', '# F\n\n## Search\nUsers search.\n\n## Ordering\nBuy (REQ-ORDER-001, REQ-ORDER-002).\n\n## Gaps\n- Search is not specified.\n\n### Later\n- More.\n'),
    }));
    expect(diagnostics.map((d) => [d.code, d.message])).toEqual([['DOC_UNCITED_SECTION', '"Search" cites nothing']]);
  });

  it('warns when no document cites a requirement', () => {
    const { status, diagnostics } = docsStatus(profile, 'docs', inputs, refs, texts({
      features: fresh('features', '# F\n\n## A\nX (REQ-ORDER-001).\n'),
      flows: fresh('flows', '# Fl\n\n## B\nY (REQ-ORDER-001).\n'),
    }));
    expect(status.uncovered).toEqual(['REQ-ORDER-002']);
    expect(diagnostics.map((d) => [d.code, d.severity])).toEqual([['DOC_UNCOVERED', 'warning']]);
  });

  it('warns when a document other than decisions.md cites a superseded decision', () => {
    const superseded = setup({
      'comb/decisions.md': `${DECISIONS_MD.replace('- **Change:** seed-orders', '- **Change:** seed-orders\n- **Superseded by:** D-022')}\n## D-022: New price rule\n- **Date:** 2026-10-08\n\nRule.\n\n**Why:** w\n`,
    });
    const doc = (id: string, body: string) => stampDoc(`<!-- generated by comb -->\n${body}`, sourceHash(profile.outputs.find((o) => o.id === id)!.sources, superseded.inputs));
    const { diagnostics } = docsStatus(profile, 'docs', superseded.inputs, superseded.refs, new Map([
      ['docs/features.md', doc('features', '# F\n\n## A\nPrice is fixed (REQ-ORDER-001, REQ-ORDER-002, D-021).\n')],
      ['docs/decisions.md', doc('decisions', '# D\n\n## P\nD-021 was replaced by D-022.\n')],
    ]));
    expect(diagnostics.filter((d) => d.code === 'DOC_CITES_SUPERSEDED').map((d) => [d.target?.file, d.severity])).toEqual([['docs/features.md', 'warning']]);
  });

  describe('section citations', () => {
    const SHIPPING_SPEC = '---\nprefix: SHIP\n---\n# shipping\n\n## Purpose\nShipping.\n\n## Allowed transitions\nshipped → delivered.\n\n## 状態\n発送済み、配達済み。\n\n## Requirements\n\n### Requirement: REQ-SHIP-001 Ship\nShip it.\n\n#### Scenario: s\n- **GIVEN** a paid order\n- **WHEN** it ships\n- **THEN** it is shipped\n';
    const shipping = setup({ 'comb/specs/shipping/spec.md': SHIPPING_SPEC });
    const status = (features: string) => {
      const doc = (id: string, body: string) => stampDoc(`<!-- generated by comb -->\n${body}`, sourceHash(profile.outputs.find((o) => o.id === id)!.sources, shipping.inputs));
      return docsStatus(profile, 'docs', shipping.inputs, shipping.refs, new Map([
        ['docs/features.md', doc('features', `# F\n\n## Ordering\nBuy and pay (REQ-ORDER-001, REQ-ORDER-002, REQ-SHIP-001).\n\n${features}`)],
      ])).diagnostics.filter((d) => d.code !== 'DOC_MISSING');
    };

    it('cites a section of a spec by its heading, with spaces, in Japanese or in another case', () => {
      expect(status('## Money\nWhole yen (order-lifecycle#Conventions).\n\n## Shipping\nMoves on (shipping#Allowed transitions; shipping#状態を参照).\n\n## About\nOrders (order-lifecycle#purpose).\n')).toEqual([]);
    });

    it('rejects a section that is not in the spec, and Requirements, listing the sections', () => {
      const ds = status('## Money\nWhole yen (order-lifecycle#Convention, order-lifecycle#Requirements).\n');
      expect(ds.map((d) => [d.code, d.target?.id, d.fix])).toEqual([
        ['REF_UNKNOWN_SECTION', 'order-lifecycle#Convention', 'Sections of order-lifecycle: Purpose, Conventions'],
        ['REF_UNKNOWN_SECTION', 'order-lifecycle#Requirements', 'Sections of order-lifecycle: Purpose, Conventions'],
      ]);
    });

    it('does not take links or other x#y for citations', () => {
      const ds = status('## Links\nSee [gaps](features.md#gaps), https://example.com/order-lifecycle#Purpose and issue#12.\n');
      expect(ds.map((d) => [d.code, d.message])).toEqual([['DOC_UNCITED_SECTION', '"Links" cites nothing']]);
    });
  });

  it('tells how to cite a question when the date was kept', () => {
    const { diagnostics } = docsStatus(profile, 'docs', inputs, refs, texts({
      'open-questions': fresh('open-questions', '# O\n\n## Q\n- Z (2026-10-06-tighten-payment#Q-1)\n'),
    }));
    expect(diagnostics.map((d) => [d.code, d.fix])).toEqual([['REF_UNKNOWN_QUESTION', 'Cite it as tighten-payment#Q-1 (without the date)']]);
  });
});

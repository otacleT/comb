import { describe, expect, it } from 'vitest';
import { docHeader, stampDoc } from '../../../src/core/docs/header.js';
import type { DocSource } from '../../../src/core/docs/profile.js';
import { docRefs, sourceFiles, sourceHash, type DocInputs } from '../../../src/core/docs/sources.js';
import { loadArchivedQuestions, loadProject } from '../../../src/core/project/load.js';
import { TIGHTEN_QUESTIONS } from '../../helpers/archive.js';
import { CONFIG_YAML, DECISIONS_MD, ORDER_SPEC } from '../../helpers/fixtures.js';
import { makeProject } from '../../helpers/project.js';

const base: DocInputs = {
  context: 'A shop',
  specs: [
    { file: 'comb/specs/a/spec.md', text: 'A' },
    { file: 'comb/specs/b/spec.md', text: 'B' },
  ],
  decisions: { file: 'comb/decisions.md', text: 'D' },
  questions: [{ change: 'x', folder: '2026-10-06-x', file: 'comb/changes/archive/2026-10-06-x/questions.md', text: 'Q' }],
};
const h = (sources: DocSource[], inputs: DocInputs = base) => sourceHash(sources, inputs);

describe('sourceHash', () => {
  it('changes only when a declared source changes', () => {
    const newDecisions = { ...base, decisions: { file: 'comb/decisions.md', text: 'D2' } };
    expect(h(['specs'], newDecisions)).toBe(h(['specs']));
    expect(h(['decisions'], newDecisions)).not.toBe(h(['decisions']));
    const newContext = { ...base, context: 'A market' };
    expect(h(['specs'], newContext)).toBe(h(['specs']));
    expect(h(['config', 'specs'], newContext)).not.toBe(h(['config', 'specs']));
    const newQuestions = { ...base, questions: [{ ...base.questions[0]!, text: 'Q2' }] };
    expect(h(['open-questions'], newQuestions)).not.toBe(h(['open-questions']));
    expect(h(['specs'], newQuestions)).toBe(h(['specs']));
    expect(h(['specs'])).toMatch(/^sha256:[0-9a-f]{16}$/);
  });

  it('does not depend on the order of the sources or of the spec files', () => {
    expect(h(['specs', 'config'])).toBe(h(['config', 'specs']));
    expect(h(['specs'], { ...base, specs: [...base.specs].reverse() })).toBe(h(['specs']));
  });

  it('lists the files an output reads', () => {
    expect(sourceFiles(['config', 'specs'], base)).toEqual(['comb/config.yaml', 'comb/specs/a/spec.md', 'comb/specs/b/spec.md']);
    expect(sourceFiles(['open-questions'], base)).toEqual(['comb/changes/archive/2026-10-06-x/questions.md']);
    expect(sourceFiles(['decisions'], { ...base, decisions: null })).toEqual([]);
  });
});

describe('loadArchivedQuestions and docRefs', () => {
  it('reads archived questions under the change id without its date, also when the id starts with digits', () => {
    const root = makeProject({
      'comb/config.yaml': CONFIG_YAML,
      'comb/changes/archive/2026-10-08-2fa-login/questions.md': '# Questions\n',
      'comb/changes/archive/2026-10-07-no-questions/proposal.md': '# x\n',
    });
    expect(loadArchivedQuestions(root).map((q) => [q.change, q.file])).toEqual([['2fa-login', 'comb/changes/archive/2026-10-08-2fa-login/questions.md']]);
  });

  it('collects the ids documents may cite', () => {
    const root = makeProject({
      'comb/config.yaml': CONFIG_YAML,
      'comb/specs/order-lifecycle/spec.md': ORDER_SPEC,
      'comb/decisions.md': DECISIONS_MD,
      'comb/changes/archive/2026-10-06-tighten-payment/questions.md': TIGHTEN_QUESTIONS,
    });
    const refs = docRefs(loadProject(root), loadArchivedQuestions(root));
    expect([...refs.requirements]).toEqual(['REQ-ORDER-001', 'REQ-ORDER-002']);
    expect([...refs.retired]).toEqual(['REQ-ORDER-010']);
    expect([...refs.decisions]).toEqual(['D-021']);
    expect([...refs.questions.get('tighten-payment')!]).toEqual(['Q-1']);
  });
});

describe('document header', () => {
  it('recognizes the bare marker, the stamped header and user files', () => {
    expect(docHeader('<!-- generated by comb -->\n# A\n')).toEqual({ generated: true, hash: null });
    const stamped = stampDoc('<!-- generated by comb -->\n# A\n', 'sha256:0123456789abcdef');
    expect(stamped).toBe('<!-- generated by comb from sha256:0123456789abcdef; edit the specs, not this file -->\n# A\n');
    expect(docHeader(stamped)).toEqual({ generated: true, hash: 'sha256:0123456789abcdef' });
    expect(docHeader('# My notes\n<!-- generated by comb -->\n')).toEqual({ generated: false, hash: null });
    expect(stampDoc('<!-- generated by comb -->', 'sha256:0123456789abcdef')).toBe(
      '<!-- generated by comb from sha256:0123456789abcdef; edit the specs, not this file -->\n',
    );
  });
});
